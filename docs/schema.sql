            detection_count integer NOT NULL CHECK (detection_count > 0),
            frp_sum_mw double precision CHECK
                (frp_sum_mw >= 0 AND frp_sum_mw < 'Infinity'::float8),
            frp_known_count integer NOT NULL CHECK
                (frp_known_count BETWEEN 0 AND detection_count),
            uncertainty jsonb NOT NULL,
            UNIQUE (job_id,sensor_code,day,grid_x,grid_y)
        );

CREATE INDEX ix_aggregate_cell ON harmonized_aggregates USING gist(cell);

CREATE INDEX ix_aggregate_job_day ON harmonized_aggregates(job_id,day);

