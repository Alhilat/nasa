    );

CREATE FUNCTION set_raw_record_hash() RETURNS trigger AS $$
    DECLARE source source_files%ROWTYPE;
    BEGIN
        SELECT * INTO STRICT source FROM source_files WHERE id=NEW.source_id;
        NEW.record_hash := encode(sha256(convert_to(jsonb_build_array(
            COALESCE(NEW.sensor_code,source.sensor_code),
            COALESCE(NULLIF(NEW.raw_properties->>'version',''),source.product_version),
            source.processing_level, NEW.raw_properties)::text,'UTF8')), 'hex');
        RETURN NEW;
    END; $$ LANGUAGE plpgsql;

CREATE TRIGGER hash_raw_record BEFORE INSERT ON raw_records
        FOR EACH ROW EXECUTE FUNCTION set_raw_record_hash();

