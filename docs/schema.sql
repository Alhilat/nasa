CREATE TABLE source_files (
            id uuid PRIMARY KEY,
            sha256 text NOT NULL UNIQUE CHECK (sha256 ~ '^[a-f0-9]{64}$'),
            original_filename text NOT NULL,
            source_url text NOT NULL,
            sensor_code text NOT NULL REFERENCES sensors(code),
            product_version text NOT NULL,
            processing_level text NOT NULL CHECK (processing_level IN ('nrt','standard')),
            retrieved_at timestamptz NOT NULL,
            imported_at timestamptz NOT NULL DEFAULT now(),
            row_count integer NOT NULL CHECK (row_count > 0),
            original_bytes bytea NOT NULL,
            source_metadata jsonb NOT NULL DEFAULT '{}'
        );

CREATE TABLE raw_observations (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            source_id uuid NOT NULL REFERENCES source_files(id),
            source_row integer NOT NULL CHECK (source_row > 0),
            sensor_code text NOT NULL REFERENCES sensors(code),
            acquired_at timestamptz NOT NULL,
            latitude double precision NOT NULL CHECK (latitude BETWEEN -90 AND 90),
            longitude double precision NOT NULL CHECK (longitude BETWEEN -180 AND 180),
            location geometry(Point,4326) GENERATED ALWAYS AS
                (ST_SetSRID(ST_MakePoint(longitude, latitude),4326)) STORED,
            frp_mw double precision CHECK
                (frp_mw >= 0 AND frp_mw < 'Infinity'::float8),
            confidence_native text NOT NULL,
            confidence_class text NOT NULL CHECK (confidence_class IN ('low','nominal','high')),
            daynight text CHECK (daynight IN ('D','N')),
            scan_km double precision CHECK (scan_km > 0 AND scan_km < 'Infinity'::float8),
            track_km double precision CHECK (track_km > 0 AND track_km < 'Infinity'::float8),
            raw_properties jsonb NOT NULL,
            uncertainty jsonb NOT NULL,
            UNIQUE (source_id, source_row)
        );

CREATE INDEX ix_observations_location ON raw_observations USING gist(location);

CREATE INDEX ix_observations_time_sensor ON raw_observations(acquired_at,sensor_code);

CREATE INDEX ix_observations_source ON raw_observations(source_id);

CREATE TABLE processing_jobs (
            id uuid PRIMARY KEY,
            kind text NOT NULL CHECK (kind IN ('ingest','aggregate','analysis')),
            status text NOT NULL CHECK (status IN ('running','succeeded','failed')),
            algorithm_version text NOT NULL,
            parameters jsonb NOT NULL,
            started_at timestamptz NOT NULL DEFAULT now(),
            finished_at timestamptz,
            error_message text,
            output_metadata jsonb NOT NULL DEFAULT '{}',
            CHECK ((status = 'running' AND finished_at IS NULL)
                OR (status <> 'running' AND finished_at IS NOT NULL))
        );

CREATE TABLE harmonized_aggregates (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
