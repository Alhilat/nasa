"""Generate the frontend contract: python scripts/generate_calendar_types.py."""

from pathlib import Path

from app.calendar_schemas import HarmonizedCalendar

OUTPUT = Path(__file__).resolve().parents[1] / "frontend/src/calendar.types.ts"


def render_types():
    schema = HarmonizedCalendar.model_json_schema()

    def ts(value):
        if "$ref" in value:
            return value["$ref"].split("/")[-1]
        if "anyOf" in value:
            return " | ".join(ts(part) for part in value["anyOf"])
        if "enum" in value:
            return " | ".join(repr(item) for item in value["enum"])
        kind = value.get("type")
        if kind == "array":
            return f"Array<{ts(value['items'])}>"
        return {
            "string": "string",
            "integer": "number",
            "number": "number",
            "boolean": "boolean",
            "null": "null",
            "object": "Record<string, unknown>",
        }[kind]

    definitions = {**schema.get("$defs", {}), "HarmonizedCalendar": schema}
    lines = ["// Generated by scripts/generate_calendar_types.py. Do not edit by hand.", ""]
    for name, definition in definitions.items():
        lines.append(f"export type {name} = {{")
        for field, value in definition["properties"].items():
            optional = "" if field in definition.get("required", []) else "?"
            lines.append(f"  {field}{optional}: {ts(value)};")
        lines.extend(["};", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    OUTPUT.write_text(render_types(), encoding="utf-8", newline="\n")
